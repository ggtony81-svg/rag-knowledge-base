def _new_page(doc):
    page = doc.new_page(width=PAGE_W, height=PAGE_H)
    return page, MT


def _wrap(text, size, max_w):
    """按字体宽度折行，返回行列表"""
    lines, cur = [], ""
    for ch in text:
        if ch == "\n":
            lines.append(cur)
            cur = ""
            continue
        if font.text_length(cur + ch, size) > max_w and cur:
            lines.append(cur)
            cur = ch
        else:
            cur += ch
    if cur:
        lines.append(cur)
    return lines


def build(out_path):
    doc = fitz.open()
    page, y = _new_page(doc)

    def put(text, size, lh, indent=0.0, color=(0.10, 0.10, 0.12)):
        """写一段折行文本，自动翻页"""
        nonlocal page, y
        for line in _wrap(text, size, CONTENT_W - indent):
            if y + lh > PAGE_H - MB:
                page, y = _new_page(doc)
            page.insert_text(fitz.Point(ML + indent, y), line, fontsize=size,
                             fontname=FONT_NAME, fontfile=FONT_PATH, color=color)
            y += lh

    # 封面标题
    put("星海科技集团 员工手册（2026 修订版）", CHAPTER_SIZE + 3, LINE_H + 10,
        color=(0.09, 0.28, 0.52))
    put("文件编号：XH-HR-2026-001　　生效日期：2026 年 1 月 1 日　　"
        "发布部门：人力资源部", BODY_SIZE - 1, LINE_H,
        color=(0.42, 0.42, 0.45))
    y += 8

    for chapter, articles in CONTENT:
        if y + LINE_H * 3 > PAGE_H - MB:
            page, y = _new_page(doc)
        y += 6
        put(chapter, CHAPTER_SIZE, LINE_H + 6, color=(0.09, 0.28, 0.52))
        y += 2
        for title, body in articles:
            put(title, TITLE_SIZE, LINE_H + 3, indent=8, color=(0.10, 0.10, 0.12))
            put(body, BODY_SIZE, LINE_H, indent=8)
            y += 4

    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    doc.save(out_path)
    n = doc.page_count
    doc.close()

    total_chars = sum(len(b) + len(t) for _, arts in CONTENT for t, b in arts)
    print(f"已生成: {out_path}")
    print(f"页数  : {n}")
    print(f"章节  : {len(CONTENT)} 章 / {sum(len(a) for _, a in CONTENT)} 条")
    print(f"正文字数: 约 {total_chars} 字")


if __name__ == "__main__":
    build(OUT_PATH)
