"""
RAG 完整流程演示
把文字转成向量 → 存到数据库 → 按意思搜索 → 拼接提问
"""
from sentence_transformers import SentenceTransformer
import numpy as np

# ============================================================
# 第1步：准备文档（模拟公司知识库）
# ============================================================
documents = [
    "入职满一年员工可享受5天年假，满10年可享受10天年假",
    "年假需提前3个工作日通过OA系统申请",
    "春节放假7天，国庆放假7天，元旦放假3天",
    "病假需提供二级以上医院开具的证明",
    "事假全年累计不得超过15天，需部门主管审批",
    "薪资每月15日发放，遇节假日提前",
    "加班可申请调休或按1.5倍工资计算加班费",
    "社保公积金缴纳基数为上年度月平均工资",
]

print("=" * 60)
print("📚 公司知识库共 8 条文档")
print()

# ============================================================
# 第2步：加载 Embedding 模型（把文字转成向量）
# ============================================================
print("⏳ 正在加载 Embedding 模型...")
model = SentenceTransformer("BAAI/bge-small-zh-v1.5")
print("✅ 模型加载完成！")
print()

# ============================================================
# 第3步：把所有文档转成向量（向量化）
# ============================================================
print("⏳ 正在把文档转成向量...")
doc_vectors = model.encode(documents)
print(f"✅ 8 条文档 → 8 个向量，每个向量 {len(doc_vectors[0])} 维")
print()

# ============================================================
# 第4步：用户提问
# ============================================================
questions = [
    "我想请假几天出去玩",
    "工资什么时候发",
    "加班有没有钱拿",
]

for question in questions:
    print("-" * 60)
    print(f"🙋 用户问：『{question}』")
    print()

    # ============================================================
    # 第5步：把问题也转成向量
    # ============================================================
    q_vector = model.encode([question])

    # ============================================================
    # 第6步：计算问题跟每条文档的相似度
    # ============================================================
    from sklearn.metrics.pairwise import cosine_similarity
    similarities = cosine_similarity(q_vector, doc_vectors)[0]

    # 找出最相似的 2 条
    top_indices = np.argsort(similarities)[-2:][::-1]

    print(f"🔍 找回最相关的 2 条文档：")
    for idx in top_indices:
        print(f"   相似度 {similarities[idx]:.2f} → {documents[idx]}")
    print()

    # ============================================================
    # 第7步：拼接 prompt，模拟让大模型回答
    # ============================================================
    context = "\n".join([documents[i] for i in top_indices])

    prompt = f"""
基于以下资料回答问题。

资料：
{context}

问题：{question}

要求：只基于资料回答，如果资料里没有相关信息就说"资料中没有相关信息"。
"""

    # 模拟大模型回复（真实场景这里调 DeepSeek/OpenAI 接口）
    # 这里我们用一段模拟回复代替
    print(f"📝 拼接后的 Prompt（就是发给大模型的完整指令）：")
    print(prompt[:200] + "...")
    print()
    print("🤖 大模型会基于资料给出准确的回答，而不是胡编。")
    print()

print("=" * 60)
print("💡 关键理解：")
print("  用户问『我想请假几天出去玩』→ 没有出现『年假』二字")
print("  但向量搜索找到了『年假』『事假』相关文档 ← 因为意思相近")
print("  这就是『搜意思』而不是『搜关键词』")
