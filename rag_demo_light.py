"""
RAG 流程演示（纯 Python 版，无需装任何包）
"""

print("=" * 60)
print("📚 RAG 完整流程演示")
print()

# ============================================================
# 第1步：准备文档（公司知识库）
# ============================================================
documents = [
    "入职满一年员工可享受5天年假，满10年可享受10天年假",
    "年假需提前3个工作日通过OA系统申请",
    "春节放假7天，国庆放假7天，元旦放假3天",
    "病假需提供二级以上医院开具的证明",
    "事假全年累计不得超过15天，需部门主管审批",
    "薪资每月15日发放，遇节假日提前",
    "加班可申请调休或按1.5倍工资计算加班费",
]

print("公司知识库共有", len(documents), "条文档：")
for i, doc in enumerate(documents):
    print(f"  {i+1}. {doc}")
print()

# ============================================================
# 第2步：模拟向量搜索
# 真实世界：用 embedding 模型把问题转成向量
#           然后跟所有文档的向量算『相似度』
# 这里直接给『相似度』，让你看流程
# ============================================================
test_cases = [
    {
        "question": "我想请假出去旅游",
        # 每条文档跟这个问题的相似度（0-1）
        "scores": [0.92, 0.85, 0.45, 0.30, 0.88, 0.10, 0.05],
        "说明": "请假旅游 → 搜到：年假规定(92%)、事假规定(88%)、年假申请(85%)"
    },
    {
        "question": "工资什么时候发",
        "scores": [0.10, 0.05, 0.20, 0.05, 0.10, 0.95, 0.35],
        "说明": "工资 → 搜到：薪资发放(95%)  ← 没有『工资』俩字但意思匹配"
    },
    {
        "question": "加班有没有钱拿",
        "scores": [0.15, 0.30, 0.15, 0.05, 0.10, 0.20, 0.93],
        "说明": "加班 → 搜到：加班费(93%)"
    },
]

# 对每个问题
for case in test_cases:
    print("=" * 60)
    print(f"🙋 用户问：『{case["question"]}』")
    print()

    # ============================================================
    # 第3步：找到最相关的文档
    # 把所有文档按相似度排序，取前2名
    # ============================================================
    # 把(文档, 相似度) 配对
    scored = list(zip(documents, case["scores"]))
    # 按相似度从高到低排序
    scored.sort(key=lambda x: x[1], reverse=True)
    # 取前2条
    top2 = scored[:2]

    print(f"🔍 向量搜索找到最相关的资料：")
    for doc, score in top2:
        print(f"   相关度 {score:.0%} → {doc}")
    print()

    # ============================================================
    # 第4步：把资料 + 问题拼在一起，发给大模型
    # ============================================================
    context = "\n".join([doc for doc, _ in top2])

    prompt = f"""基于以下资料回答问题。

资料：
{context}

问题：{case["question"]}

要求：只基于资料回答，如果资料里没有就说不知道。"""

    print(f"📤 发给大模型的 prompt（上下文 + 问题 拼在一起）：")
    print(prompt)
    print()

    # ============================================================
    # 第5步：模拟大模型回复
    # ============================================================
    print(f"🤖 大模型基于资料的回复：", end="")
    if "请假" in case["question"] or "旅游" in case["question"]:
        print("根据公司制度，您可以使用年假或事假。"
              "年假需提前3个工作日申请，事假全年累计不超过15天。")
    elif "工资" in case["question"]:
        print("薪资每月15日发放，如遇节假日会提前发放。")
    elif "加班" in case["question"]:
        print("加班可以申请调休或按1.5倍工资计算加班费。")
    print()

    print(f"📎 {case["说明"]}")
    print()

# ============================================================
# 总结
# ============================================================
print("=" * 60)
print("✅ RAG 核心流程总结：")
print()
print("  用户问『工资什么时候发』")
print("       ↓")
print("  ① 问题转成向量（一串数字）")
print("  ② 去数据库找『向量最像』的文档")
print("     → 找到『薪资每月15日发放』（相似度95%）")
print("  ③ 把文档 + 问题发给大模型")
print("  ④ 模型基于资料回答 → 准确、不瞎编")
print()
print("  💡 『工资』≠『薪资』 → 但向量认为它们意思相近")
print("     这就是 RAG 比关键词搜索强的地方")
